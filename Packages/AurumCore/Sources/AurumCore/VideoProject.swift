    public init(presetID: String, duration: Seconds = 1.5, title: String? = nil) {
        self.presetID = presetID
        self.duration = duration
        self.title = title
    }
}

/// A video edit: clips in order, one look stack graded over everything,
/// timed layers, music and optional intro and outro. Serialisable like
/// `EditDocument`, and undoable through `Undoable<VideoProject>`.
public struct VideoProject: Codable, Equatable, Identifiable, Sendable {
    public static let currentSchemaVersion = 1

    public var schemaVersion: Int
    public var id: UUID
    public var clips: [Clip]
    /// Looks and adjustments graded over every clip, same model as photos.
    public var operations: [EditOperation]
    /// Animated effects over time (flicker, light leaks, shake...).
    public var effects: [AnimatedEffect]
    public var aspect: AspectPreset
    public var layers: [TimedLayer]
    public var music: MusicSelection?
    public var intro: BookendEffect?
    public var outro: BookendEffect?
    /// The template this project was built from, if any.
    public var templateID: String?
    public var createdAt: Date
    public var modifiedAt: Date

    public init(id: UUID = UUID(), clips: [Clip] = [], operations: [EditOperation] = [], effects: [AnimatedEffect] = [], aspect: AspectPreset = .story, layers: [TimedLayer] = [], music: MusicSelection? = nil, intro: BookendEffect? = nil, outro: BookendEffect? = nil, templateID: String? = nil, createdAt: Date = Date()) {
        self.schemaVersion = Self.currentSchemaVersion
        self.id = id
        self.clips = clips
        self.operations = operations
        self.effects = effects
        self.aspect = aspect
        self.layers = layers
        self.music = music
        self.intro = intro
        self.outro = outro
        self.templateID = templateID
        self.createdAt = createdAt
        self.modifiedAt = createdAt
    }

    // MARK: Timing

    /// Where each clip starts on the timeline. Transitions overlap the
    /// incoming clip with the end of the previous one.
    public var clipStartTimes: [Seconds] {
        var starts: [Seconds] = []
        var t = intro?.duration ?? 0
        for (i, clip) in clips.enumerated() {
            if i > 0 {
                let overlap = min(clip.transitionIn.duration, clip.duration / 2, clips[i - 1].duration / 2)
                t -= overlap
            }
            starts.append(t)
            t += clip.duration
        }
        return starts
    }

    /// Total length including intro and outro.
    public var duration: Seconds {
        guard let lastStart = clipStartTimes.last, let last = clips.last else {
            return (intro?.duration ?? 0) + (outro?.duration ?? 0)
        }
        return lastStart + last.duration + (outro?.duration ?? 0)
    }

    /// The clip on screen at time t (the incoming one during a transition)
    /// and the local time within it.
    public func clip(at t: Seconds) -> (index: Int, local: Seconds)? {
        let starts = clipStartTimes
        for i in clips.indices.reversed() where t >= starts[i] {
            let local = t - starts[i]
            return local < clips[i].duration ? (i, local) : nil
        }
        return nil
    }

    // MARK: Editing

    public mutating func append(_ clip: Clip) {
        clips.append(clip)
    }

    public mutating func moveClip(from source: Int, to destination: Int) {
        guard clips.indices.contains(source) else { return }
        let clip = clips.remove(at: source)
        clips.insert(clip, at: min(max(destination, 0), clips.count))
    }

    public mutating func removeClip(id: UUID) {
        clips.removeAll { $0.id == id }
    }

    /// Splits the clip under timeline time t into two. Returns false if t is
    /// too close to either end to leave two usable pieces.
    @discardableResult
    public mutating func split(at t: Seconds) -> Bool {
        guard let (index, local) = clip(at: t) else { return false }
        let clip = clips[index]
        guard local >= Clip.minimumDuration, clip.duration - local >= Clip.minimumDuration else { return false }
        let cut = clip.sourceTime(atLocal: local)
        var first = clip
        var second = clip
        second.id = UUID()
        second.transitionIn = .cut
        if clip.isReversed {
            first.trimStart = cut
            second.trimEnd = cut
        } else {
            first.trimEnd = cut
            second.trimStart = cut
        }
        clips[index] = first
        clips.insert(second, at: index + 1)
        return true
    }

    public mutating func updateClip(id: UUID, _ change: (inout Clip) -> Void) {
        guard let i = clips.firstIndex(where: { $0.id == id }) else { return }
        change(&clips[i])
    }

    // MARK: Serialisation

    public func encoded() throws -> Data {
        try EditDocument.makeEncoder().encode(self)
    }

    public static func decode(from data: Data) throws -> VideoProject {
        try EditDocument.makeDecoder().decode(VideoProject.self, from: data)
    }
}

/// Undo/redo for any value type, with the same transaction model as `EditHistory`.
public struct Undoable<Value: Equatable & Sendable>: Equatable, Sendable {
    private var snapshots: [Value]
    private var cursor = 0
    private var transactionBase: Value?
    public let limit: Int

    public init(_ initial: Value, limit: Int = 100) {
        self.snapshots = [initial]
        self.limit = max(2, limit)
    }

    public var current: Value { snapshots[cursor] }
    public var canUndo: Bool { cursor > 0 && transactionBase == nil }
    public var canRedo: Bool { cursor < snapshots.count - 1 && transactionBase == nil }

    public mutating func commit(_ value: Value) {
        if let base = transactionBase {
            transactionBase = nil
            snapshots[cursor] = base
            guard value != base else { return }
        } else {
            guard value != current else { return }
        }
        if cursor < snapshots.count - 1 { snapshots.removeSubrange((cursor + 1)...) }
        snapshots.append(value)
        if snapshots.count > limit { snapshots.removeFirst(snapshots.count - limit) }
        cursor = snapshots.count - 1
    }

    public mutating func update(_ value: Value) {
        if transactionBase == nil { transactionBase = current }
        snapshots[cursor] = value
    }

    public mutating func cancelTransaction() {
        guard let base = transactionBase else { return }
        snapshots[cursor] = base
        transactionBase = nil
    }

    @discardableResult
    public mutating func undo() -> Value? {
        guard canUndo else { return nil }
        cursor -= 1
        return current
    }

    @discardableResult
    public mutating func redo() -> Value? {
        guard canRedo else { return nil }
        cursor += 1
        return current
    }
}
