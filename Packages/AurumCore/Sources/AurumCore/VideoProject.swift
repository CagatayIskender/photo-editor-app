import Foundation

/// Time in seconds. Plain Doubles keep Core free of CoreMedia; the renderer
/// converts to CMTime with a 600 timescale.
public typealias Seconds = Double

/// One piece of media on the timeline: a video clip or a still photo shown
/// for a fixed duration.
public struct Clip: Codable, Equatable, Identifiable, Sendable {
    public enum Kind: String, Codable, Sendable { case video, photo }

    public var id: UUID
    public var kind: Kind
    public var source: SourceAsset
    /// Length of the source media (for photos, the default still duration).
    public var sourceDuration: Seconds
    /// The used part of the source, in source time.
    public var trimStart: Seconds
    public var trimEnd: Seconds
    /// Playback speed: 0.25 (slow motion) to 4.
    public var speed: Double
    public var isReversed: Bool
    /// Clip audio volume, 0...1. Photos have no audio.
    public var volume: Double
    /// Transition into this clip from the previous one.
    public var transitionIn: Transition

    public static let speedRange: ClosedRange<Double> = 0.25...4.0
    public static let minimumDuration: Seconds = 0.2

    public init(id: UUID = UUID(), kind: Kind, source: SourceAsset, sourceDuration: Seconds, trimStart: Seconds = 0, trimEnd: Seconds? = nil, speed: Double = 1, isReversed: Bool = false, volume: Double = 1, transitionIn: Transition = .cut) {
        self.id = id
        self.kind = kind
        self.source = source
        self.sourceDuration = max(sourceDuration, Clip.minimumDuration)
        self.trimStart = max(0, trimStart)
        self.trimEnd = min(trimEnd ?? sourceDuration, max(sourceDuration, Clip.minimumDuration))
        self.speed = Clip.speedRange.clamp(speed)
        self.isReversed = isReversed
        self.volume = (0.0...1.0).clamp(volume)
        self.transitionIn = transitionIn
    }

    /// A still photo shown for `duration` seconds.
    public static func photo(_ source: SourceAsset, duration: Seconds = 3) -> Clip {
        Clip(kind: .photo, source: source, sourceDuration: duration)
    }

    /// How long the clip lasts on the timeline, after trimming and speed.
    public var duration: Seconds { (trimEnd - trimStart) / speed }

    /// The source time shown at `local` seconds into the clip.
    public func sourceTime(atLocal local: Seconds) -> Seconds {
        let t = min(max(local, 0), duration) * speed
        return isReversed ? trimEnd - t : trimStart + t
    }

    /// Sets the trim, keeping at least the minimum duration inside the source.
    public mutating func trim(start: Seconds, end: Seconds) {
        let s = min(max(0, start), sourceDuration - Clip.minimumDuration)
        let e = max(min(sourceDuration, end), s + Clip.minimumDuration)
        trimStart = s
        trimEnd = e
    }

    public mutating func setSpeed(_ value: Double) {
        speed = Clip.speedRange.clamp(value)
    }
}

/// How one clip hands over to the next. `ai` is generated by the backend
/// (Phase 3) and falls back to a dissolve until the result arrives.
public enum Transition: Codable, Equatable, Sendable {
    case cut
    case dissolve(duration: Seconds)
    case dipToBlack(duration: Seconds)
    case slide(duration: Seconds)
    case zoom(duration: Seconds)
    case ai(jobID: String?, duration: Seconds)

    public var duration: Seconds {
        switch self {
        case .cut: return 0
        case .dissolve(let d), .dipToBlack(let d), .slide(let d), .zoom(let d), .ai(_, let d): return d
        }
    }

    enum CodingKeys: String, CodingKey { case type, duration, jobID }
    enum Tag: String, Codable { case cut, dissolve, dipToBlack, slide, zoom, ai }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        let d = try c.decodeIfPresent(Double.self, forKey: .duration) ?? 0.5
        switch try c.decode(Tag.self, forKey: .type) {
        case .cut: self = .cut
        case .dissolve: self = .dissolve(duration: d)
        case .dipToBlack: self = .dipToBlack(duration: d)
        case .slide: self = .slide(duration: d)
        case .zoom: self = .zoom(duration: d)
        case .ai: self = .ai(jobID: try c.decodeIfPresent(String.self, forKey: .jobID), duration: d)
        }
    }

    public func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        switch self {
        case .cut: try c.encode(Tag.cut, forKey: .type)
        case .dissolve(let d): try c.encode(Tag.dissolve, forKey: .type); try c.encode(d, forKey: .duration)
        case .dipToBlack(let d): try c.encode(Tag.dipToBlack, forKey: .type); try c.encode(d, forKey: .duration)
        case .slide(let d): try c.encode(Tag.slide, forKey: .type); try c.encode(d, forKey: .duration)
        case .zoom(let d): try c.encode(Tag.zoom, forKey: .type); try c.encode(d, forKey: .duration)
        case .ai(let job, let d):
            try c.encode(Tag.ai, forKey: .type)
            try c.encode(d, forKey: .duration)
            try c.encodeIfPresent(job, forKey: .jobID)
        }
    }
}

/// Simple in and out animations for layers (no keyframes, by design).
public enum LayerAnimation: String, Codable, CaseIterable, Sendable {
    case none, fade, rise, drop, zoom, typewriter, shimmer

    public var displayName: String {
        switch self {
        case .none: return "None"
        case .fade: return "Fade"
        case .rise: return "Rise"
        case .drop: return "Drop"
        case .zoom: return "Zoom"
        case .typewriter: return "Typewriter"
        case .shimmer: return "Shimmer"
        }
    }
}

/// A text, sticker or image layer shown for part of the video.
public struct TimedLayer: Codable, Equatable, Identifiable, Sendable {
    public var id: UUID { overlay.id }
    public var overlay: Overlay
    public var start: Seconds
    public var end: Seconds
    public var animationIn: LayerAnimation
    public var animationOut: LayerAnimation
    /// Length of each animation.
    public var animationDuration: Seconds

    public init(overlay: Overlay, start: Seconds, end: Seconds, animationIn: LayerAnimation = .fade, animationOut: LayerAnimation = .fade, animationDuration: Seconds = 0.4) {
        self.overlay = overlay
        self.start = max(0, start)
        self.end = max(end, start + Clip.minimumDuration)
        self.animationIn = animationIn
        self.animationOut = animationOut
        self.animationDuration = animationDuration
    }

    public func isVisible(at t: Seconds) -> Bool { t >= start && t < end }

    /// Progress of the in (0→1) or out (1→0) animation at time t; 1 when fully shown.
    public func presence(at t: Seconds) -> Double {
        guard isVisible(at: t) else { return 0 }
        let d = max(animationDuration, 0.001)
        let inP = animationIn == .none ? 1 : min(1, (t - start) / d)
        let outP = animationOut == .none ? 1 : min(1, (end - t) / d)
        return max(0, min(inP, outP))
    }
}

/// Background music for the whole video.
public struct MusicSelection: Codable, Equatable, Sendable {
    public enum Source: Codable, Equatable, Sendable {
        /// A track from AURUM's licensed library, by catalogue ID.
        case library(trackID: String)
        /// A file the user imported, by its bookmark in the app's container.
        case imported(fileName: String)
    }

    public var source: Source
    public var title: String
    /// Where in the track the video starts.
    public var startOffset: Seconds
    public var volume: Double
    public var fadeIn: Seconds
    public var fadeOut: Seconds
    /// Beat grid from beat detection, used to cut templates on the beat.
    public var beats: BeatGrid?

    public init(source: Source, title: String, startOffset: Seconds = 0, volume: Double = 0.8, fadeIn: Seconds = 0.5, fadeOut: Seconds = 1, beats: BeatGrid? = nil) {
        self.source = source
        self.title = title
        self.startOffset = max(0, startOffset)
        self.volume = (0.0...1.0).clamp(volume)
        self.fadeIn = max(0, fadeIn)
        self.fadeOut = max(0, fadeOut)
        self.beats = beats
    }

    /// Volume multiplier at video time t, applying fades over `total` seconds.
    public func gain(at t: Seconds, total: Seconds) -> Double {
        var g = volume
        if fadeIn > 0, t < fadeIn { g *= max(0, t / fadeIn) }
        if fadeOut > 0, t > total - fadeOut { g *= max(0, (total - t) / fadeOut) }
        return g
    }
}

/// Animated opening or closing card for a photo or video.
public struct BookendEffect: Codable, Equatable, Sendable {
    public var presetID: String
