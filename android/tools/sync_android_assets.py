#!/usr/bin/env python3
"""Copies AURUM's shared sources of truth into the Android app.

The iOS app and the Android app read the same catalogues, brand file, fonts,
sticker artwork and translations. This script is the only thing that writes
the Android copies, so the repository root stays the single source of truth:

    Looks/catalog.json                 -> app/src/main/assets/looks/catalog.json
    Content/{templates,bookends,drops,music}.json
                                       -> app/src/main/assets/content/
    Brand/brand.json                   -> app/src/main/assets/brand/brand.json
    App/Fonts/*.ttf                    -> app/src/main/res/font/<snake_case>.ttf (bytes unchanged)
    App/Fonts/licenses/*.txt           -> app/src/main/assets/licenses/
    App/Assets.xcassets/sticker.*/*.svg-> app/src/main/res/drawable/sticker_*.xml (VectorDrawable)
    App/Localizable.xcstrings          -> app/src/main/res/values{,-tr}/strings.xml
      + android/l10n/android_strings.json (Android-only wording, e.g. no "iPhone")
                                       -> app/src/main/java/com/aurum/app/l10n/L10nKeys.kt

Usage (from anywhere):
    python3 android/tools/sync_android_assets.py           # write
    python3 android/tools/sync_android_assets.py --check   # verify, exit 1 if stale

--check also fails when app code calls tr("...") with a key that has no string.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from svg_to_vector import convert as svg_to_vector  # noqa: E402

ANDROID = HERE.parent
REPO = ANDROID.parent
APP = ANDROID / "app" / "src" / "main"
ASSETS = APP / "assets"
RES = APP / "res"
KOTLIN_KEYS = APP / "java" / "com" / "aurum" / "app" / "l10n" / "L10nKeys.kt"
OVERRIDES = ANDROID / "l10n" / "android_strings.json"

GENERATED_NOTE = "Generated by android/tools/sync_android_assets.py from the shared sources. Do not edit."

COPIES = {
    "Looks/catalog.json": "looks/catalog.json",
    "Content/templates.json": "content/templates.json",
    "Content/bookends.json": "content/bookends.json",
    "Content/drops.json": "content/drops.json",
    "Content/music.json": "content/music.json",
    "Brand/brand.json": "brand/brand.json",
}


def font_resource_name(stem: str) -> str:
    """Same rule as OverlayFont.resourceName in core: PlayfairDisplay-Italic -> playfair_display_italic."""
    return re.sub(r"([a-z])([A-Z])", r"\1_\2", stem).replace("-", "_").lower()


# ---------------------------------------------------------------- strings

SPEC = re.compile(r"%(?:(\d+)\$)?(lld|ld|d|@|f|\.\d+f|%)")


def to_android_format(text: str, positional: bool) -> tuple[str, int]:
    """Converts Swift format specifiers to Java ones. Returns (text, argument count)."""
    count = 0

    def repl(m: re.Match) -> str:
        nonlocal count
        explicit, kind = m.group(1), m.group(2)
        if kind == "%":
            return "%%"
        count += 1
        index = int(explicit) if explicit else count
        java = {"lld": "d", "ld": "d", "d": "d", "@": "s", "f": "f"}.get(kind, kind)
        return f"%{index}${java}" if positional else f"%{java}"

    out = SPEC.sub(repl, text)
    return out, count


def argument_count(text: str) -> int:
    return sum(1 for m in SPEC.finditer(text) if m.group(2) != "%")


def escape_android(text: str) -> str:
    s = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s


def resource_names(keys: list[str]) -> dict[str, str]:
    names: dict[str, str] = {}
    used: set[str] = set()
    for key in keys:
        slug = re.sub(r"[^a-z0-9]+", "_", key.lower()).strip("_")[:48].strip("_") or "text"
        name = "s_" + slug
        if name in used:
            name = f"{name}_{hashlib.sha1(key.encode()).hexdigest()[:6]}"
        used.add(name)
        names[key] = name
    return names


def load_strings() -> dict[str, dict[str, str]]:
    """key -> {"en": ..., "tr": ...}, from the xcstrings plus Android overrides."""
    catalog = json.loads((REPO / "App" / "Localizable.xcstrings").read_text(encoding="utf-8"))
    source = catalog.get("sourceLanguage", "en")
    table: dict[str, dict[str, str]] = {}
    for key, entry in catalog["strings"].items():
        locs = entry.get("localizations", {})
        en = locs.get(source, {}).get("stringUnit", {}).get("value", key)
        tr = locs.get("tr", {}).get("stringUnit", {}).get("value")
        table[key] = {"en": en, "tr": tr or en}
    overrides = json.loads(OVERRIDES.read_text(encoding="utf-8"))
    for key, value in overrides.items():
        if key.startswith("//"):
            continue
        table[key] = {"en": value.get("en", key), "tr": value.get("tr", value.get("en", key))}
    return table


def strings_xml(table: dict[str, dict[str, str]], names: dict[str, str], lang: str) -> str:
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {GENERATED_NOTE} -->", "<resources>"]
    for key in sorted(table):
        text = table[key][lang]
        positional = argument_count(key) > 1 or argument_count(text) > 1
        converted, count = to_android_format(text, positional)
        attrs = f'name="{names[key]}"'
        if count == 0 and "%" in converted:
            attrs += ' formatted="false"'
            converted = converted.replace("%%", "%")
        lines.append(f"    <string {attrs}>{escape_android(converted)}</string>")
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def kotlin_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n").replace("\t", "\\t") + '"'


def keys_kotlin(table: dict[str, dict[str, str]], names: dict[str, str]) -> str:
    entries = "\n".join(f"        {kotlin_string(k)} to R.string.{names[k]}," for k in sorted(table))
    return f"""// {GENERATED_NOTE}
package com.aurum.app.l10n

import com.aurum.app.R

/**
 * Maps the English source strings used as keys on iOS (Localizable.xcstrings)
 * to Android string resources, so screens can call tr("Begin") like SwiftUI's
 * Text("Begin") and both apps share one translation table.
 */
internal object L10nKeys {{
    val ids: Map<String, Int> = hashMapOf(
{entries}
    )
}}
"""


# ---------------------------------------------------------------- plan

def plan() -> dict[Path, bytes]:
    """Every generated file and its exact bytes."""
    out: dict[Path, bytes] = {}
    for src, dst in COPIES.items():
        out[ASSETS / dst] = (REPO / src).read_bytes()
    for lic in sorted((REPO / "App" / "Fonts" / "licenses").glob("*.txt")):
        out[ASSETS / "licenses" / lic.name] = lic.read_bytes()
    for ttf in sorted((REPO / "App" / "Fonts").glob("*.ttf")):
        out[RES / "font" / f"{font_resource_name(ttf.stem)}.ttf"] = ttf.read_bytes()
    for svg in sorted((REPO / "App" / "Assets.xcassets").glob("sticker.*.imageset/*.svg")):
        sticker_id = svg.parent.name[len("sticker."):-len(".imageset")]
        name = "sticker_" + sticker_id.replace("-", "_")
        xml = svg_to_vector(svg.read_text(encoding="utf-8"), note=f"{GENERATED_NOTE} Source: {svg.relative_to(REPO)}")
        out[RES / "drawable" / f"{name}.xml"] = xml.encode("utf-8")
    table = load_strings()
    names = resource_names(sorted(table))
    out[RES / "values" / "strings.xml"] = strings_xml(table, names, "en").encode("utf-8")
    out[RES / "values-tr" / "strings.xml"] = strings_xml(table, names, "tr").encode("utf-8")
    out[KOTLIN_KEYS] = keys_kotlin(table, names).encode("utf-8")
    return out


def stale_generated(files: dict[Path, bytes]) -> list[Path]:
    """Generated files on disk that no source produces any more."""
    stale = []
    for pattern in ["drawable/sticker_*.xml", "font/*.ttf"]:
        for p in RES.glob(pattern):
            if p not in files:
                stale.append(p)
    for folder in ["looks", "content", "brand", "licenses"]:
        for p in (ASSETS / folder).glob("*") if (ASSETS / folder).exists() else []:
            if p not in files:
                stale.append(p)
    return stale


def missing_keys() -> list[tuple[str, str]]:
    """tr("...") calls in app code whose key has no string."""
    table = load_strings()
    missing = []
    call = re.compile(r'\btr\(\s*"((?:[^"\\]|\\.)*)"')
    for kt in sorted((APP / "java").rglob("*.kt")):
        if kt == KOTLIN_KEYS:
            continue
        for m in call.finditer(kt.read_text(encoding="utf-8")):
            key = m.group(1).encode().decode("unicode_escape").replace("\\$", "$") if "\\" in m.group(1) else m.group(1)
            if key not in table:
                missing.append((str(kt.relative_to(ANDROID)), key))
    return missing


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify the Android copies are current; write nothing")
    args = parser.parse_args()

    files = plan()
    problems: list[str] = []
    for path, data in files.items():
        current = path.read_bytes() if path.exists() else None
        if current == data:
            continue
        if args.check:
            problems.append(f"stale: {path.relative_to(REPO)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            print(f"wrote {path.relative_to(REPO)}")
    for path in stale_generated(files):
        if args.check:
            problems.append(f"orphaned: {path.relative_to(REPO)}")
        else:
            path.unlink()
            print(f"removed {path.relative_to(REPO)}")
    for where, key in missing_keys():
        problems.append(f"missing string: {key!r} used in {where}")

    if problems:
        print("\n".join(problems), file=sys.stderr)
        if args.check:
            print("Run: python3 android/tools/sync_android_assets.py", file=sys.stderr)
        return 1
    print("Android assets are up to date." if args.check else f"{len(files)} files in sync.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
